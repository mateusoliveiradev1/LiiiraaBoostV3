function rebaseForTypeScript(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map((entry) => rebaseForTypeScript(entry));
  }

  if (!isJsonObject(value)) {
    return value;
  }

  const rebased: JsonObject = {};

  for (const [key, entry] of Object.entries(value)) {
    if (key === '$ref' && typeof entry === 'string' && entry.endsWith('.json')) {
      rebased[key] = `#/$defs/${entry.slice(0, -'.json'.length)}`;
      continue;
    }

    if (
      key === 'unevaluatedProperties' &&
      isJsonObject(entry) &&
      isJsonObject(entry['not']) &&
      Object.keys(entry['not']).length === 0
    ) {
      rebased['additionalProperties'] = false;
      continue;
    }

    rebased[key] = rebaseForTypeScript(entry);
  }

  return rebased;
}

function normalizeGeneratedText(value: string): string {
  return `${value.replaceAll('\r\n', '\n').trimEnd()}\n`;
}

function normalizeForRustTransport(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map((entry) => normalizeForRustTransport(entry));
  }

  if (!isJsonObject(value)) {
    return value;
  }

  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => key !== 'uniqueItems' && key !== 'pattern')
      .map(([key, entry]) => [key, normalizeForRustTransport(entry)]),
  );
}

const typescriptStage: GenerationStage = {
  name: 'typescript-transports',
  async generate(): Promise<readonly GeneratedArtifact[]> {
    const definitions = requireDefinitions(await canonicalSchema());
    const generatorSchema = rebaseForTypeScript({
      title: 'GeneratedContractRoots',
      type: 'object',
      properties: {
        messageEnvelope: transportMessageRoot(),
        webDocument: webDocumentRoot(),
        controlPlaneDocument: controlPlaneDocumentRoot(),
      },
      required: ['messageEnvelope', 'webDocument', 'controlPlaneDocument'],
      $defs: definitions,
    });

    if (!isJsonObject(generatorSchema)) {
      throw new Error('Could not build TypeScript transport generator schema.');
    }

    const models = await compileTypeScript(generatorSchema, 'GeneratedContractRoots', {
      additionalProperties: false,
      bannerComment: GENERATED_TYPESCRIPT_HEADER,
      style: {
        singleQuote: true,
      },
      unknownAny: false,
      unreachableDefinitions: true,
    });
    const transportAliases = [
      "export type MessageEnvelope = GeneratedContractRoots['messageEnvelope'];",
      "export type WebDocument = GeneratedContractRoots['webDocument'];",
      "export type ControlPlaneDocument = GeneratedContractRoots['controlPlaneDocument'];",
    ].join('\n');

    return [
      {
        path: OUTPUT_PATHS.typescriptModels,
        value: normalizeGeneratedText(`${models}\n${transportAliases}`),
      },
      {
        path: OUTPUT_PATHS.typescriptIndex,
        value: normalizeGeneratedText(
          `${GENERATED_TYPESCRIPT_HEADER}\n\nexport type * from './models.js';\nexport { controlPlaneDocumentValidator } from './standalone-validators.js';`,
        ),
      },
    ];
  },
};

function executeFile(
  command: string,
  arguments_: readonly string[],
  workingDirectory: string,
): Promise<string> {
  return new Promise((resolvePromise, rejectPromise) => {
    execFile(
      command,
      arguments_,
      {
        cwd: workingDirectory,
        encoding: 'utf8',
        maxBuffer: 16 * 1024 * 1024,
        windowsHide: true,
      },
      (error, stdout, stderr) => {
        if (error !== null) {
          rejectPromise(
            new Error(
              `${command} ${arguments_.join(' ')} failed:\n${stderr.trim() || error.message}`,
            ),
          );
          return;
        }

        resolvePromise(stdout);
      },
    );
  });
}

