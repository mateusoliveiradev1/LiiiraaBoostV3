function isJsonObject(value: unknown): value is JsonObject {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map((entry) => canonicalize(entry));
  }

  if (isJsonObject(value)) {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([key, entry]) => [key, canonicalize(entry)]),
    );
  }

  return value;
}

function stableJson(value: unknown): string {
  return `${JSON.stringify(canonicalize(value), null, 2)}\n`;
}

function requireControlPlaneOperations(program: Program): void {
  let namespace: Namespace = program.getGlobalNamespaceType();
  for (const segment of ['Liiiraa', 'Contracts', 'Desktop', 'V1']) {
    const nested = namespace.namespaces.get(segment);
    if (nested === undefined) {
      throw new Error(`Canonical TypeSpec namespace is missing ${segment}.`);
    }
    namespace = nested;
  }

  for (const operation of ['getAccount', 'issueAdminCommand']) {
    if (!namespace.operations.has(operation)) {
      throw new Error(`Canonical TypeSpec control-plane operation is missing ${operation}.`);
    }
  }
}

export function assertKnownOutputPath(path: string): void {
  const resolvedPath = resolve(path);
  if (!KNOWN_OUTPUT_PATHS.has(resolvedPath)) {
    throw new Error(`Refusing to write unowned generation path: ${resolvedPath}`);
  }
}

function expectRejectedPath(path: string): void {
  try {
    assertKnownOutputPath(path);
  } catch {
    return;
  }

  throw new Error(`Bounded path policy accepted forbidden path: ${path}`);
}

export function verifyBoundedPathPolicy(): void {
  for (const path of KNOWN_OUTPUT_PATHS) {
    assertKnownOutputPath(path);
  }

  expectRejectedPath(join(REPOSITORY_ROOT, 'package.json'));
  expectRejectedPath(join(OUTPUT_ROOT, 'unexpected.schema.json'));
  expectRejectedPath(join(OUTPUT_ROOT, '..', 'outside-generated.json'));
}

function requireDefinitions(bundle: JsonObject): JsonObject {
  const definitions = bundle['$defs'];
  if (!isJsonObject(definitions)) {
    throw new Error('TypeSpec JSON Schema bundle is missing $defs.');
  }

  for (const definitionName of REQUIRED_DEFINITIONS) {
    if (!isJsonObject(definitions[definitionName])) {
      throw new Error(`TypeSpec JSON Schema bundle is missing ${definitionName}.`);
    }
  }

  return definitions;
}

function collectReferencedDefinitionNames(value: unknown, names: Set<string>): void {
  if (Array.isArray(value)) {
    for (const entry of value) {
      collectReferencedDefinitionNames(entry, names);
    }
    return;
  }

  if (!isJsonObject(value)) {
    return;
  }

  const reference = value['$ref'];
  if (typeof reference === 'string' && reference.endsWith('.json')) {
    names.add(reference.slice(0, -'.json'.length));
  }

  for (const entry of Object.values(value)) {
    collectReferencedDefinitionNames(entry, names);
  }
}

function reachableDefinitions(
  definitions: JsonObject,
  rootNames: readonly string[],
  family: string,
): JsonObject {
  const selectedNames = new Set<string>(rootNames);
  const pendingNames = [...selectedNames];

  while (pendingNames.length > 0) {
    const name = pendingNames.pop();
    if (name === undefined) {
      continue;
    }

    const definition = definitions[name];
    if (!isJsonObject(definition)) {
      throw new Error(`TypeSpec JSON Schema bundle missing ${family} dependency ${name}.`);
    }

    const referencedNames = new Set<string>();
    collectReferencedDefinitionNames(definition, referencedNames);
    for (const referencedName of referencedNames) {
      if (!selectedNames.has(referencedName)) {
        selectedNames.add(referencedName);
        pendingNames.push(referencedName);
      }
    }
  }

  return Object.fromEntries(
    Object.entries(definitions).filter(([name]) => selectedNames.has(name)),
  );
}

function inspectionDefinitions(definitions: JsonObject): JsonObject {
  return reachableDefinitions(
    definitions,
    ['DiagnosticValue', 'InspectSystemRequest', 'InspectSystemResult'],
    'desktop inspection',
  );
}

function desktopDefinitions(definitions: JsonObject): JsonObject {
  return reachableDefinitions(
    definitions,
    [
      'DiagnosticValue',
      'HostToRendererShellEvent',
      'InspectSystemRequest',
      'InspectSystemResult',
      'RendererToHostShellCommand',
    ],
    'desktop',
  );
}

function webDefinitions(definitions: JsonObject): JsonObject {
  const selectedDefinitions = reachableDefinitions(definitions, WEB_DOCUMENT_ROOTS, 'web');

  for (const name of WEB_DEFINITION_NAMES) {
    if (!(name in selectedDefinitions)) {
      throw new Error(`Web document schema does not reach required definition ${name}.`);
    }
  }

  return selectedDefinitions;
}

function controlPlaneDefinitions(definitions: JsonObject): JsonObject {
  const emittedRoots = CONTROL_PLANE_DEFINITION_NAMES.filter((name) =>
    isJsonObject(definitions[name]),
  );
  return reachableDefinitions(definitions, emittedRoots, 'control-plane');
}

function createRuntimeSchema(
  schemaId: string,
  definitions: JsonObject,
  root: JsonObject,
): JsonObject {
  const referencedNames = new Set<string>();
  collectReferencedDefinitionNames(root, referencedNames);
  collectReferencedDefinitionNames(definitions, referencedNames);
  const unresolvedNames = [...referencedNames]
    .filter((name) => !(name in definitions))
    .sort((left, right) => left.localeCompare(right));
  if (unresolvedNames.length > 0) {
    throw new Error(
      `Runtime schema ${schemaId} has unresolved local references: ${unresolvedNames.join(', ')}.`,
    );
  }

  return {
    $schema: SCHEMA_DIALECT,
    $id: schemaId,
    'x-liiiraa-generated': GENERATED_HEADER,
    $defs: definitions,
    ...root,
  };
}

